export const TRANSLATIONS: Record<LangCode, TranslationMap> = {
  'zh-CN': ZH_CN,
  'zh-TW': ZH_TW,
  en: EN,
  ko: KO,
  ja: JA,
  es: ES,
};

export function t(lang: LangCode, key: keyof TranslationMap, vars?: Record<string, string | number>): string {
  let str = TRANSLATIONS[lang][key] ?? TRANSLATIONS['zh-CN'][key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replace(`{${k}}`, String(v));
    }
  }
  return str;
}
